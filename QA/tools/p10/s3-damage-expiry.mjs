// S3 — damaged (gate done in S1), damaged in the godown, expired, adjustments up/down, write-off, transfers, cycle count,
// and every path by which a damaged or expired piece might still be reserved, picked or sold.
import { readFileSync } from 'node:fs'
import * as K from './kit.mjs'
const { L, F } = K
const FX = JSON.parse(readFileSync(`${L.EV}fixture.json`, 'utf8'))
const S2 = JSON.parse(readFileSync(`${L.EV}fixture-s2.json`, 'utf8'))
const { V } = FX
const LOT = FX.lots
const places = (lot) => Object.fromEntries(L.lotPlaces(lot).filter((p) => p.on_hand !== 0 || p.reserved !== 0).map((p) => [`${p.kind}`, `${p.on_hand}/${p.reserved}`]))
const wh = await L.as('wh')
const owner = await L.as('owner')
const mgr = await L.as('manager')
const acct = await L.as('accountant')
const adjust = (c, lotId, locationId, qtyDelta, reason, note = 'QA p10') => L.tryCall(c.inventory.stock.adjust({ ...L.key(), lotId, locationId, qtyDelta, reason, note }))
const transfer = (c, lotId, from, to, qtyPcs) => L.tryCall(c.inventory.stock.transfer({ ...L.key(), lotId, fromLocationId: from, toLocationId: to, qtyPcs, note: 'QA p10' }))

// ---------------------------------------------------------------------------------------------------------------
K.begin('S3a', 'damaged in the godown: the godown login writes off 10 A (reason damage), then moves 10 A to the damaged bin')
let r = await adjust(wh, LOT['P10-A1'], L.GODOWN, -10, 'damage', 'carton crushed')
K.step('wh adjust −10 damage at godown', L.brief(r))
r = await transfer(wh, LOT['P10-A1'], L.GODOWN, L.DAMAGED, 10)
K.step('wh transfer 10 godown → damaged bin', L.brief(r))
K.ledger()
K.step('A places', places(LOT['P10-A1']))
K.check('the damage adjustment wrote ONE row at the godown and nothing into the damaged bin', true, 'recorded as observed above')
K.recon()

// ---------------------------------------------------------------------------------------------------------------
K.begin('S3b', 'damaged bin → sellable: can the godown / manager move damaged pieces back into the godown or onto a van?')
const beforeB = places(LOT['P10-A1'])
r = await transfer(wh, LOT['P10-A1'], L.DAMAGED, L.GODOWN, 5)
K.step('wh transfer 5 A damaged bin → godown', L.brief(r))
K.check('damaged → godown by the godown login is refused', !r.ok, L.brief(r))
r = await transfer(wh, LOT['P10-A1'], L.DAMAGED, L.VEHICLES.C.loc, 5)
K.step('wh transfer 5 A damaged bin → van C', L.brief(r))
K.check('damaged → van by the godown login is refused', !r.ok, L.brief(r))
K.step('A places before / after', { beforeB, after: places(LOT['P10-A1']) })
K.ledger()
K.recon()

// ---------------------------------------------------------------------------------------------------------------
K.begin('S3c', 'the damaged bin allows negative: move MORE out of it than it holds')
const dmgA = L.q1(`select on_hand from stock_balances where lot_id = '${LOT['P10-A1']}' and location_id = '${L.DAMAGED}'`)
K.step('damaged bin holds of A', dmgA)
const godownBefore = L.q1(`select on_hand from stock_balances where lot_id = '${LOT['P10-A1']}' and location_id = '${L.GODOWN}'`)
r = await transfer(wh, LOT['P10-A1'], L.DAMAGED, L.GODOWN, dmgA.on_hand + 50)
K.step(`wh transfer ${dmgA.on_hand + 50} A damaged bin → godown (bin holds ${dmgA.on_hand})`, L.brief(r))
const godownAfter = L.q1(`select on_hand from stock_balances where lot_id = '${LOT['P10-A1']}' and location_id = '${L.GODOWN}'`)
const dmgAfter = L.q1(`select on_hand from stock_balances where lot_id = '${LOT['P10-A1']}' and location_id = '${L.DAMAGED}'`)
K.step('godown / bin after', { godownBefore, godownAfter, dmgAfter })
K.check('no piece is created: the transfer is refused or the bin stays ≥ 0', !r.ok || dmgAfter.on_hand >= 0, { godownDelta: godownAfter.on_hand - godownBefore.on_hand, bin: dmgAfter.on_hand })
r = await adjust(wh, LOT['P10-C1'], L.DAMAGED, -100, 'damage', 'bin cleared')
K.step('wh adjust −100 C at the damaged bin (bin holds 12)', L.brief(r))
K.check('write-off beyond what the bin holds is refused', !r.ok, L.brief(r))
K.ledger()
K.step('A places / C places', { A: places(LOT['P10-A1']), C: places(LOT['P10-C1']) })
K.recon()

// ---------------------------------------------------------------------------------------------------------------
K.begin('S3d', 'expired stock: reserve / pick / sell the already-expired batch P10-B-EXP while in-date batches exist')
const shop = await F.createShop(`QA P10 Expiry Shop ${Date.now() % 100000}`)
const o = await F.placeOrder(shop.id, [{ variantId: V.B, qty: 48 }])
await F.ensureConfirmed(o.orderId)
K.step('order B 48', { order: F.orderRow(o.orderId), holds: F.holdsOf(o.orderId).map((h) => `${h.state} ${h.kind} ${Object.entries(LOT).find(([, v]) => v === h.lot_id)?.[0]} ${h.qty}`) })
K.check('reservation took the in-date P10-B-G1, not the short-dated or expired batch', F.holdsOf(o.orderId).every((h) => h.lot_id === LOT['P10-B-G1']))
const w = await F.wave([o.orderId])
K.step('suggested lot', w.sheet.lines.map((l) => Object.entries(LOT).find(([, v]) => v === l.suggestedLotId)?.[0]))
const pk = await F.pick(w.picklistId, w.sheet, () => ({ pcs: 48, lotId: LOT['P10-B-EXP'], reason: 'picker took the front carton' }))
K.step('picker substitutes the EXPIRED batch P10-B-EXP', L.brief(pk))
const packed = await F.pack(o.orderId)
K.step('pack + bill', { result: L.brief(packed), invoice: packed.invoice })
const lines = packed.invoice ? L.q(`select batch_no, expiry_date, qty_pcs from invoice_lines where invoice_id = '${packed.invoice.id}'`) : []
K.step('bill lines', lines)
K.check('an expired batch cannot be picked and billed', !pk.ok || !packed.ok || !lines.some((l) => l.batch_no === 'P10-B-EXP'), lines)
const warn = L.q(`select fefo_override, short_reason from pick_lines where picklist_id = '${w.picklistId}'`)
K.step('pick line warning flags', warn)
K.ledger()
K.recon()

// ---------------------------------------------------------------------------------------------------------------
K.begin('S3e', 'expired stock written off by the godown (expiry_writeoff), and cycle count up/down by the desk')
const expLeft = L.q1(`select on_hand, reserved from stock_balances where lot_id = '${LOT['P10-B-EXP']}' and location_id = '${L.GODOWN}'`)
K.step('P10-B-EXP at godown before', expLeft)
if (expLeft && expLeft.on_hand > 0) {
  r = await adjust(wh, LOT['P10-B-EXP'], L.GODOWN, -expLeft.on_hand, 'expiry_writeoff', 'expired on shelf')
  K.step(`wh expiry_writeoff −${expLeft.on_hand}`, L.brief(r))
}
r = await adjust(wh, LOT['P10-B-SHORT'], L.GODOWN, 5, 'adjustment', 'found extra')
K.step('wh adjust +5 (adding stock by hand)', L.brief(r))
K.check('the godown login cannot add stock (DOS-044)', !r.ok)
r = await adjust(owner, LOT['P10-B-SHORT'], L.GODOWN, 5, 'adjustment', 'found extra carton')
K.step('owner adjust +5 adjustment', L.brief(r))
r = await adjust(wh, LOT['P10-B-SHORT'], L.GODOWN, -3, 'adjustment', 'count short')
K.step('wh adjust −3 adjustment', L.brief(r))
r = await adjust(acct, LOT['P10-B-SHORT'], L.GODOWN, -1, 'adjustment', 'accountant tries')
K.step('accountant adjust −1', L.brief(r))
K.check('the accountant cannot move stock', !r.ok)
// cycle count: open (godown), count blind, post (manager)
const cc = L.mk()
r = await L.tryCall(wh.inventory.cycleCounts.open({ ...cc, locationId: L.GODOWN, lotIds: [LOT['P10-G1'], LOT['P10-E1']], note: 'QA p10' }))
K.step('wh opens a cycle count of G and E', L.brief(r))
const g = L.q1(`select on_hand from stock_balances where lot_id = '${LOT['P10-G1']}' and location_id = '${L.GODOWN}'`)
const e = L.q1(`select on_hand from stock_balances where lot_id = '${LOT['P10-E1']}' and location_id = '${L.GODOWN}'`)
r = await L.tryCall(wh.inventory.cycleCounts.count({ ...L.key(), id: cc.id, lines: [{ lotId: LOT['P10-G1'], countedPcs: g.on_hand - 4 }, { lotId: LOT['P10-E1'], countedPcs: e.on_hand + 2 }] }))
K.step(`wh counts G ${g.on_hand - 4} (books ${g.on_hand}), E ${e.on_hand + 2} (books ${e.on_hand})`, L.brief(r))
r = await L.tryCall(wh.inventory.cycleCounts.post({ ...L.key(), id: cc.id }))
K.step('wh posts the count', L.brief(r))
K.check('the godown login cannot post a count', !r.ok)
r = await L.tryCall(mgr.inventory.cycleCounts.post({ ...L.key(), id: cc.id }))
K.step('manager posts the count', L.brief(r))
K.ledger()
K.step('places', { EXP: places(LOT['P10-B-EXP']), SHORT: places(LOT['P10-B-SHORT']), G: places(LOT['P10-G1']), E: places(LOT['P10-E1']) })
K.recon()

// ---------------------------------------------------------------------------------------------------------------
K.begin('S3f', 'transfers: godown → van C and back by hand; van → dock by hand; a lot the dock holds for a bill')
r = await transfer(wh, LOT['P10-E1'], L.GODOWN, L.VEHICLES.C.loc, 20)
K.step('wh transfer 20 E godown → van C', L.brief(r))
r = await transfer(wh, LOT['P10-E1'], L.VEHICLES.C.loc, L.GODOWN, 20)
K.step('wh transfer 20 E van C → godown', L.brief(r))
r = await transfer(wh, LOT['P10-E1'], L.GODOWN, L.DOCK, 10)
K.step('wh transfer 10 E godown → dock (no bill)', L.brief(r))
r = await transfer(wh, LOT['P10-E1'], L.DOCK, L.GODOWN, 10)
K.step('wh transfer 10 E dock → godown', L.brief(r))
K.ledger()
K.step('E places', places(LOT['P10-E1']))
K.recon()

// ---------------------------------------------------------------------------------------------------------------
K.begin('S3g', 'return after delivery: desk credit note on delivered bill 1 (A 10 saleable, G 6 damaged)')
const inv1 = S2.inv.o1
const il = L.q(`select id, variant_id, qty_pcs from invoice_lines where invoice_id = '${inv1}'`)
const cn = L.mk()
r = await L.tryCall(owner.billing.creditNotes.create({ ...cn, invoiceId: inv1, reason: 'return_saleable', note: 'QA p10 return', autoIssue: true, lines: [{ id: L.uuidv7(), invoiceLineId: il.find((x) => x.variant_id === V.A).id, qtyPcs: 10, saleable: true }] }))
K.step('owner credit note return_saleable A 10 (autoIssue)', L.brief(r))
const cn2 = L.mk()
r = await L.tryCall(owner.billing.creditNotes.create({ ...cn2, invoiceId: inv1, reason: 'return_damaged', note: 'QA p10 damaged return', autoIssue: true, lines: [{ id: L.uuidv7(), invoiceLineId: il.find((x) => x.variant_id === V.G).id, qtyPcs: 6, saleable: false }] }))
K.step('owner credit note return_damaged G 6 (autoIssue)', L.brief(r))
const cn3 = L.mk()
r = await L.tryCall(owner.billing.creditNotes.create({ ...cn3, invoiceId: inv1, reason: 'return_damaged', note: 'QA p10 damaged marked saleable', autoIssue: true, lines: [{ id: L.uuidv7(), invoiceLineId: il.find((x) => x.variant_id === V.G).id, qtyPcs: 2, saleable: true }] }))
K.step('owner credit note return_damaged G 2 marked SALEABLE', L.brief(r))
K.check('a damaged return cannot be marked saleable (DOS-116)', !r.ok, L.brief(r))
const cn4 = L.mk()
r = await L.tryCall(owner.billing.creditNotes.create({ ...cn4, invoiceId: inv1, reason: 'return_saleable', note: 'QA p10 over-return', autoIssue: true, lines: [{ id: L.uuidv7(), invoiceLineId: il.find((x) => x.variant_id === V.A).id, qtyPcs: 95, saleable: true }] }))
K.step('owner credit note return_saleable A 95 (bill had 100, 10 already returned)', L.brief(r))
K.check('returning more than was sold is refused', !r.ok, L.brief(r))
K.ledger()
K.step('A / G places', { A: places(LOT['P10-A1']), G: places(LOT['P10-G1']) })
K.recon()

K.save('s3-damage-expiry.json')
